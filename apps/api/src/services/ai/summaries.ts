/**
 * The story so far: a whole story, or a story up to a reader's chapter, in one
 * paragraph (Task AI 6).
 *
 * **Map-reduce, over summaries.** A story is never sent to a model whole --
 * forty chapters do not fit a small context window, and stuffing a large one
 * degrades the answer as well as the bill. Instead:
 *
 * 1. **Map.** Each chapter has its own two-or-three sentence summary, the same
 *    row the reader's "previously" recap uses (`ensureChapterSummary` in
 *    `recap.ts`), cached by a hash of the chapter's text and the prompt
 *    versions. A chapter too long for one call is itself map-reduced there.
 * 2. **Reduce.** The chapter summaries, in order, are reduced into one
 *    paragraph. A story with more than `REDUCE_BATCH` chapters is reduced in
 *    two levels: runs of chapters into a paragraph each, then those
 *    paragraphs into one. The reduce prompt only ever sees summaries.
 *
 * **Spoiler-free by construction.** A summary up to chapter N is reduced from
 * the summaries of chapters 1..N and nothing else, and each of those was
 * written from its own chapter alone. There is no ending in the prompt for the
 * model to keep secret. The bound is the reader's, resolved by Ask This Book's
 * rules (`resolveAskSetting`): their chosen chapter, their reading position, the
 * first chapter if they have none, and the whole story for its author.
 *
 * **Cached by its input.** `sourceHash` covers the chapter summaries it was
 * reduced from and the prompt versions. Editing chapter 3 changes chapter 3's
 * summary, which changes the hash of every story summary from chapter 3 on --
 * and leaves chapters 1-2 alone. Unchanged text is never summarised again.
 *
 * **Who pays.** A reader's missing summary is generated by a background job
 * (`summary.story`, AI 20's queue) as the platform's own work: it is a shared
 * artefact, generated once per story and bound until the text changes, and the
 * next reader at that chapter gets it for free. An author's "Regenerate" runs
 * as the author.
 *
 * Over published chapters of a listed story only: this is what readers see,
 * and a draft is nobody's but its author's.
 */

import { createHash } from "node:crypto";
import { Temporal } from "temporal-polyfill";
import { logger } from "../../lib/logger.js";
import { enqueue } from "../../lib/jobs.js";
import { db } from "../../prisma/db.js";
import { resolveAskSetting, type AskScope } from "./ask-book.js";
import { loadAiConfig } from "./config.js";
import { SUMMARY_STORY_JOB } from "./job-schedule.js";
import {
  STORY_SUMMARY_PROMPT,
  STORY_SUMMARY_SYSTEM_PROMPT,
  storySummaryMessage,
  type SummaryItem,
} from "./prompts/summary.js";
import { aiProvider } from "./provider.js";
import { chapterSummaryHash, ensureChapterSummary } from "./recap.js";

const FEATURE = "summary.story";

/** Chapter summaries per reduce call; past this, reduce in two levels. */
export const REDUCE_BATCH = 12;

/** One paragraph, with room for a reasoning model's thinking. */
const MAX_TOKENS = 700;

interface PublishedChapter {
  id: string;
  number: number;
  title: string;
  content: string;
}

async function publishedChapters(storyId: string): Promise<PublishedChapter[]> {
  const rows = await db.orm.content.Chapter.select("id", "chapterNumber", "title", "content")
    .where((chapter) => chapter.storyId.eq(storyId))
    .where((chapter) => chapter.publishedAt.isNotNull())
    .orderBy((chapter) => chapter.chapterNumber.asc())
    .all();
  return rows.map((row) => ({ id: row.id, number: row.chapterNumber, title: row.title, content: row.content }));
}

function toIso(value: unknown): string | null {
  if (value === null || value === undefined) return null;
  if (value instanceof Temporal.Instant) return value.toString();
  if (value instanceof Date) return value.toISOString();
  return String(value);
}

/**
 * The hash a summary of these chapters must carry to be current, or null
 * when some chapter's summary is missing or stale -- in which case the story
 * summary is stale too, whatever it says.
 */
async function currentSourceHash(chapters: PublishedChapter[]): Promise<string | null> {
  if (chapters.length === 0) return null;
  const rows = await db.orm.ai.ChapterSummary.select("chapterId", "contentHash", "text")
    .where((row) => row.chapterId.in(chapters.map((chapter) => chapter.id)))
    .all();
  const byChapter = new Map(rows.map((row) => [row.chapterId, row]));

  const hash = createHash("sha256").update(`story@${STORY_SUMMARY_PROMPT.version}|batch${REDUCE_BATCH}|`);
  for (const chapter of chapters) {
    const row = byChapter.get(chapter.id);
    if (!row || row.contentHash !== chapterSummaryHash(chapter.content)) return null;
    // The summary text itself, not only the chapter's hash: an author's
    // "regenerate" rewrites a chapter summary without changing the chapter.
    hash.update(`${chapter.number}\u0000${row.text}\u0001`);
  }
  return hash.digest("hex");
}

/* Reading ---------------------------------------------------------------- */

export interface StorySummaryView {
  /** Generated. Labelled as such wherever it is shown. */
  text: string;
  upToChapter: number;
  /** `story` covers every published chapter; `spoiler_free` stops earlier. */
  kind: "story" | "spoiler_free";
  chapterCount: number;
  generatedAt: string | null;
}

export interface StorySummaryStatus {
  /** False when there is nothing to summarise: no published chapter in range. */
  available: boolean;
  /** Which chapters the summary may cover for this viewer, and why. */
  scope: AskScope;
  /** Null until written, and while the stored one is stale. */
  summary: StorySummaryView | null;
  /** True when a job has been queued to write it; poll again shortly. */
  generating: boolean;
}

/**
 * What a viewer should see, without calling a model -- and, when it is
 * missing or stale, a queued job to write it.
 *
 * `requested` is a chapter the reader chose; null uses their default bound.
 * Authorisation is `resolveAskSetting`'s: a story the viewer cannot see is a
 * 404 before anything is read.
 */
export async function getStorySummary(
  viewerId: string,
  storyKey: string,
  requested: number | null,
): Promise<StorySummaryStatus> {
  const setting = await resolveAskSetting(viewerId, storyKey, requested);
  const all = await publishedChapters(setting.story.id);
  const last = all.at(-1)?.number ?? 0;
  const bound = Math.min(setting.scope.upToChapter ?? last, last);
  const chapters = all.filter((chapter) => chapter.number <= bound);

  if (chapters.length === 0) {
    return { available: false, scope: setting.scope, summary: null, generating: false };
  }

  const [stored, hash] = await Promise.all([
    db.orm.ai.StorySummary.select("text", "upToChapter", "kind", "chapterCount", "sourceHash", "updatedAt")
      .where((row) => row.storyId.eq(setting.story.id))
      .where((row) => row.upToChapter.eq(bound))
      .first(),
    currentSourceHash(chapters),
  ]);

  if (stored && hash !== null && stored.sourceHash === hash) {
    return {
      available: true,
      scope: setting.scope,
      summary: {
        text: stored.text,
        upToChapter: stored.upToChapter,
        kind: stored.kind === "story" ? "story" : "spoiler_free",
        chapterCount: stored.chapterCount,
        generatedAt: toIso(stored.updatedAt),
      },
      generating: false,
    };
  }

  // Missing or stale: queue it rather than make the reader wait on a page
  // load. Debounced by story and bound, so a hundred readers at chapter 5 are
  // one job.
  let generating = false;
  if (loadAiConfig().jobs) {
    try {
      await enqueue(SUMMARY_STORY_JOB, { storyId: setting.story.id, upToChapter: bound }, {
        dedupeKey: `summary:${setting.story.id}:${bound}`,
      });
      generating = true;
    } catch (error) {
      logger.warn({ err: error }, "story summary not queued");
    }
  }
  return { available: true, scope: setting.scope, summary: null, generating };
}

/* Writing ---------------------------------------------------------------- */

export interface StorySummaryGeneration {
  summary: StorySummaryView | null;
  /** Model calls made: chapter summaries written, plus reduce calls. */
  calls: number;
  tokensUsed: number;
}

/**
 * Writes the summary of a story up to `upToChapter` (null: every published
 * chapter), or returns the stored one when its inputs have not changed.
 *
 * `force` rewrites the reduce even when current -- the author's
 * "Regenerate". It does not rewrite chapter summaries; those change when
 * their chapters do, or when an author regenerates one on its own.
 */
export async function generateStorySummary(
  storyId: string,
  upToChapter: number | null,
  options: { force?: boolean; signal?: AbortSignal } = {},
): Promise<StorySummaryGeneration> {
  const story = await db.orm.content.Story.select("title", "listedAt")
    .where((row) => row.id.eq(storyId))
    .first();
  if (!story?.listedAt) return { summary: null, calls: 0, tokensUsed: 0 };

  const all = await publishedChapters(storyId);
  const last = all.at(-1)?.number ?? 0;
  const bound = Math.min(upToChapter ?? last, last);
  const chapters = all.filter((chapter) => chapter.number <= bound);
  if (chapters.length === 0) return { summary: null, calls: 0, tokensUsed: 0 };

  let calls = 0;
  let tokensUsed = 0;

  // Map: every chapter summary in range, written only where missing or stale.
  const items: SummaryItem[] = [];
  for (const chapter of chapters) {
    const summary = await ensureChapterSummary(chapter, options.signal ? { signal: options.signal } : {});
    calls += summary.calls;
    tokensUsed += summary.tokensUsed;
    items.push({ label: `Chapter ${chapter.number}: ${chapter.title}`, text: summary.text });
  }

  const hash = await currentSourceHash(chapters);
  const stored = await db.orm.ai.StorySummary.select("id", "text", "sourceHash", "updatedAt")
    .where((row) => row.storyId.eq(storyId))
    .where((row) => row.upToChapter.eq(bound))
    .first();

  const kind: StorySummaryView["kind"] = bound === last ? "story" : "spoiler_free";
  if (stored && hash !== null && stored.sourceHash === hash && !options.force) {
    return {
      summary: { text: stored.text, upToChapter: bound, kind, chapterCount: chapters.length, generatedAt: toIso(stored.updatedAt) },
      calls,
      tokensUsed,
    };
  }

  let model = "";
  const reduce = async (part: SummaryItem[], partBound: number): Promise<string> => {
    const completion = await aiProvider().complete({
      feature: FEATURE,
      system: STORY_SUMMARY_SYSTEM_PROMPT,
      messages: [{ role: "user", content: storySummaryMessage({ storyTitle: story.title, upToChapter: partBound, items: part }) }],
      maxTokens: MAX_TOKENS,
      ...(options.signal ? { signal: options.signal } : {}),
    });
    calls += 1;
    tokensUsed += completion.usage.inputTokens + completion.usage.outputTokens;
    model = completion.usage.model;
    const text = completion.text.trim();
    if (text === "") throw new Error("The story summary came back empty.");
    return text;
  };

  // Reduce: one level for a short story, two for a long one. Each run of
  // chapters is labelled with its range, so the final reduce reads in order.
  let level = items;
  if (level.length > REDUCE_BATCH) {
    const runs: SummaryItem[] = [];
    for (let start = 0; start < chapters.length; start += REDUCE_BATCH) {
      const run = chapters.slice(start, start + REDUCE_BATCH);
      const first = run[0]!.number;
      const end = run.at(-1)!.number;
      runs.push({ label: `Chapters ${first}–${end}`, text: await reduce(items.slice(start, start + REDUCE_BATCH), end) });
    }
    level = runs;
  }
  const text = await reduce(level, bound);

  const timestamp = Temporal.Now.instant();
  const fields = {
    kind,
    text,
    sourceHash: hash ?? "",
    chapterCount: chapters.length,
    model,
    promptId: STORY_SUMMARY_PROMPT.id,
    promptVersion: STORY_SUMMARY_PROMPT.version,
    updatedAt: timestamp,
  };
  if (stored) {
    await db.orm.ai.StorySummary.where((row) => row.id.eq(stored.id)).update(fields);
  } else {
    try {
      await db.orm.ai.StorySummary.create({ storyId, upToChapter: bound, ...fields });
    } catch (error) {
      // A second writer for the same bound: theirs is as good as ours.
      logger.warn({ err: error, storyId, bound }, "story summary written twice");
    }
  }

  return {
    summary: { text, upToChapter: bound, kind, chapterCount: chapters.length, generatedAt: timestamp.toString() },
    calls,
    tokensUsed,
  };
}

/**
 * The author's "Regenerate": forget every stored summary of the story, so
 * each reader's bound is rewritten on its next read, and rewrite the
 * whole-story one now (queued, as the author).
 */
export async function regenerateStorySummaries(
  storyId: string,
  authorId: string,
  requestId: string | null,
): Promise<string> {
  await db.runtime().query(
    db.raw.sql`DELETE FROM "ai"."storySummary" WHERE "storyId" = ${storyId}`.affectedCount().build(),
  );
  return enqueue(SUMMARY_STORY_JOB, { storyId, upToChapter: null, force: true }, {
    userId: authorId,
    requestId,
    dedupeKey: `summary:${storyId}:all`,
  });
}
